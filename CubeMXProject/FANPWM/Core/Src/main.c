    rpm_ctrl_update();
    rpm_sweep_update();
    rpm_ctrl_uart_poll();
    button_ui_poll();

    /* 自動每秒印一次 S 狀態（校正中不印，避免蓋掉 CAL 訊息） */
    if (!rpm_ctrl_is_calibrating())
    {
      static uint32_t last_status_ms = 0;
      uint32_t status_period = rpm_ctrl_is_csv_logging() ? 100U : 1000U;
      if ((HAL_GetTick() - last_status_ms) >= status_period)
      {
        last_status_ms = HAL_GetTick();
        rpm_ctrl_print_status();
      }
    }
    rpm_front = fan_get_front_rpm();
